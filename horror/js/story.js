// 每章首关：把该章氛围"加冕"式铺开（开场全景 + 一句转折），强于普通关。
function buildOpening(id, ch, lib, rng, vars) {
  const opens = pickDistinct(rng, lib.open, 2);
  const turn = fill(rng.pick(lib.turn), vars);
  const narrative = [opens[0], opens[1], turn];
  return {
    title: `第 ${id} 关 · ${ch.title}`,
    narrative,
    whisper: fill(rng.pick(lib.whisper), vars)
  };
}

// 每章末关：收束本章、把玩家推向下一段下降。
function buildClosing(id, ch, lib, rng, vars) {
  const worse = fill(rng.pick(lib.worse), vars);
  const turn = fill(rng.pick(lib.turn), vars);
  const image = fill(rng.pick(lib.image), vars);
  return {
    title: `第 ${id} 关 · ${ch.title}（尽头）`,
    narrative: [image, worse, turn],
    whisper: fill(rng.pick(lib.whisper), vars)
  };
}

// 普通关：手写骨架 + 程序化组合。
// 越往关末（章内进度高）、整体越深（decay 高），越多采用 worse/turn，越少纯 image。
function buildOrdinary(id, ch, lib, rng, vars, inChapPos, decay) {
  // 段数 2..4，随深度倾向更多段。
  const segCount = rng.bool(0.25 + decay * 0.45) ? (rng.bool(0.5) ? 4 : 3) : (rng.bool(0.4) ? 3 : 2);

  // 段类型序列：首段多为 open/image（落地），随后 image，靠后倾向 worse/turn。
  const blocks = [];
  // 第一段：落地（open 或 image）
  blocks.push(rng.bool(0.45) ? "open" : "image");
  // 中间段：image 为主，恶化概率随章内位置与整体 decay 上升
  const worsen = Math.min(0.85, 0.15 + inChapPos * 0.5 + decay * 0.3);
  for (let i = 1; i < segCount - 1; i++) {
    blocks.push(rng.bool(worsen) ? "worse" : "image");
  }
  // 末段：转折/暗示（turn），偶尔 worse
  blocks.push(rng.bool(0.7) ? "turn" : "worse");

  // 各类型内不重复取句。
  const need = { open: 0, image: 0, worse: 0, turn: 0 };
  for (const b of blocks) need[b]++;
  const pool = {
    open: pickDistinct(rng, lib.open, need.open),
    image: pickDistinct(rng, lib.image, need.image),
    worse: pickDistinct(rng, lib.worse, need.worse),
    turn: pickDistinct(rng, lib.turn, need.turn)
  };
  const cursor = { open: 0, image: 0, worse: 0, turn: 0 };
  const narrative = blocks.map((b) => fill(pool[b][cursor[b]++], vars));

  // 标题：普通关用层数 + 偶尔小标题（从意象词派生），避免千篇一律。
  let title = `第 ${id} 关`;
  if (rng.bool(0.5)) {
    const sub = subtitleFor(ch, rng, vars, decay);
    title += ` · ${sub}`;
  } else {
    title += ` · ${ch.title}`;
  }

  // whisper：随深度出现概率与不安程度上升；浅层偶尔留空（留白）。
  let whisper = "";
  if (rng.bool(0.55 + decay * 0.35)) whisper = fill(rng.pick(lib.whisper), vars);

  return { title, narrative, whisper };
}

// 程序化小标题：用章主题 + 反复意象组词，给普通关一点个性。
const SUB_BANK = [
  "再下一层", "更深处", "回声", "倒数", "门", "那个声音", "薄", "冷",
  "记得", "忘了", "你不是第一个", "慢半拍", "{剩}", "不对劲", "更下面"
];
function subtitleFor(ch, rng, vars, decay) {
  // 深层更倾向"失控"的小标题
  const deepBank = ["裂", "化", "空", "陷", "替", "无名", "{剩}", "别数了"];
  const bank = decay > 0.6 ? SUB_BANK.concat(deepBank) : SUB_BANK;
  return fill(rng.pick(bank), vars);
}

