export function getNarrative(id, chapter, rng) {
  // 健壮：夹取 id，自取章节（即便调用方传错）。
  const lvl = Math.max(1, Math.min(999, Math.floor(id) || 1));
  const ch = chapter && chapter.range ? chapter : chapterOf(lvl);
  const r = safeRng(rng, lvl);

  const decay = decayOf(lvl);
  // 章内位置 0..1（用于"越接近章末越恶化"）
  const span = ch.range[1] - ch.range[0];
  const inChapPos = span > 0 ? (lvl - ch.range[0]) / span : 0;

  // 模板变量
  const remaining = 999 - lvl; // "剩余数字"：到零还剩多少（倒数意象）
  const vars = {
    层: lvl,
    剩: remaining,
    深: r.pick(DEPTH_WORDS),
    声: r.pick(VOICE_NAMES)
  };

  // 1) 里程碑：手写特写优先。
  if (MILESTONES[lvl]) {
    const m = MILESTONES[lvl];
    return {
      title: m.title,
      narrative: m.narrative.map((p) => fill(p, vars)),
      whisper: fill(m.whisper || "", vars)
    };
  }

  const lib = PALETTE[ch.n] || PALETTE[1];

  // 2) 每章首关：加冕式开场（专门处理，强于普通关）。
  if (lvl === ch.range[0]) {
    return buildOpening(lvl, ch, lib, r, vars);
  }
  // 3) 每章末关：收束本章。
  if (lvl === ch.range[1]) {
    return buildClosing(lvl, ch, lib, r, vars);
  }

  // 4) 普通关：程序化组合。
  return buildOrdinary(lvl, ch, lib, r, vars, inChapPos, decay);
}

