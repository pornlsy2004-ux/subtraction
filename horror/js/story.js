// 安全 rng：即使调用方没传，也用一个由 id 派生的退化随机源，保证健壮。
function safeRng(rng, id) {
  if (rng && typeof rng.pick === "function") return rng;
  let a = ((id || 1) * 2654435761) >>> 0;
  const next = () => {
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
  return {
    next,
    int: (lo, hi) => Math.floor(lo + next() * (hi - lo + 1)),
    float: (lo = 0, hi = 1) => lo + next() * (hi - lo),
    bool: (p = 0.5) => next() < p,
    pick: (arr) => arr[Math.floor(next() * arr.length)],
    shuffle: (arr) => {
      const x = arr.slice();
      for (let i = x.length - 1; i > 0; i--) {
        const j = Math.floor(next() * (i + 1));
        [x[i], x[j]] = [x[j], x[i]];
      }
      return x;
    }
  };
}

// 从库里不重复地取 k 个（库不足时允许回环但尽量错开）。
function pickDistinct(rng, arr, k) {
  if (!arr || arr.length === 0) return [];
  const shuffled = rng.shuffle(arr);
  const out = [];
  for (let i = 0; i < k; i++) out.push(shuffled[i % shuffled.length]);
  return out;
}

// 模板填充：{层}=层数 {剩}=剩余数字 {深}=该章内深度词 {名}=反复意象等
function fill(tpl, vars) {
  return tpl_(tpl, vars);
}
function tpl_(s, v) {
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in v ? String(v[k]) : m));
}

